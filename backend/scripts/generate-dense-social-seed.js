#!/usr/bin/env node
/**
 * Generates backend/scripts/seed-demo-social-dense.sql
 * ~40 users, 100+ posts, stories, friendships, likes, influencer instructors + endorsements.
 */
const fs = require('fs');
const path = require('path');

const PASS_HASH = 'ae68d3ddb474a3769a06f7c5e5a34bd24f5c8d42a19c1b02fcf06b3f84082beb'; // growlseed123

const CATEGORY_PATHS = [
  'fitness:losing-weight',
  'fitness:building-muscle',
  'fitness:cardio',
  'fitness:flexibility',
  'art:piano',
  'art:violin',
  'art:drawing',
  'art:photography',
  'nutrition:meal-planning',
  'nutrition:healthy-eating',
  'mindset:meditation',
  'mindset:discipline',
  'mindset:focus',
];

const CAPTIONS = [
  'Consistency over intensity today.',
  'Small win logged.',
  'Practice session done.',
  'Showing up even when motivation is low.',
  'Progress photo / checkpoint.',
  'Sharing what I learned this week.',
  'Community check-in.',
  'Form focus — slow and clean.',
  'Rest day reflection.',
  'Morning routine locked in.',
];

const IMAGE_SEEDS = [
  'https://images.unsplash.com/photo-1571019613454-1cb2f99b84d4?w=900&q=80',
  'https://images.unsplash.com/photo-1517836357483-507a3093906b?w=900&q=80',
  'https://images.unsplash.com/photo-1520523839897-bd0b52f945a0?w=900&q=80',
  'https://images.unsplash.com/photo-1513364776144-60967b0f800f?w=900&q=80',
  'https://images.unsplash.com/photo-1506126613408-eca07ce68773?w=900&q=80',
  'https://images.unsplash.com/photo-1498837167922-ddd27525d352?w=900&q=80',
  'https://images.unsplash.com/photo-1544367567-0f2fcb009e0b?w=900&q=80',
  'https://images.unsplash.com/photo-1517832207067-4db24a2ae47c?w=900&q=80',
];

const FIRST = [
  'Jordan', 'River', 'Casey', 'Morgan', 'Sam', 'Avery', 'Nina', 'Leo', 'Mia', 'Kai',
  'Quinn', 'Reese', 'Blake', 'Drew', 'Skyler', 'Parker', 'Jamie', 'Cameron', 'Hayden', 'Rowan',
  'Finley', 'Sage', 'Emerson', 'Phoenix', 'Dakota', 'Taylor', 'Alex', 'Charlie', 'Riley', 'Jesse',
  'Harper', 'Eden', 'Lane', 'Marley', 'Oakley', 'Peyton', 'Remy', 'Shannon', 'Tatum', 'Winter',
];

function esc(s) {
  return String(s).replace(/'/g, "''");
}

function parentCat(pathKey) {
  return pathKey.includes(':') ? pathKey.split(':')[0] : pathKey;
}

function subCat(pathKey) {
  return pathKey.includes(':') ? pathKey.split(':')[1] : null;
}

const lines = [];
lines.push('-- Dense social seed: ~40 users, 100+ posts, stories, friends, endorsements');
lines.push('-- Password for all dense accounts: growlseed123');
lines.push('-- Influencers (is_instructor=1): dense-u-01 .. dense-u-05');
lines.push('-- Generated by scripts/generate-dense-social-seed.js');
lines.push('');
lines.push('PRAGMA foreign_keys = ON;');
lines.push('');

// Users
lines.push('INSERT OR REPLACE INTO users (');
lines.push('  id, email, password_hash, points, is_instructor, is_business, metadata,');
lines.push('  email_verified, email_verification_token_hash, email_verification_expires_at,');
lines.push('  created_at, updated_at');
lines.push(') VALUES');

const userRows = [];
for (let i = 1; i <= 40; i++) {
  const id = `dense-u-${String(i).padStart(2, '0')}`;
  const email = `demo-${String(i).padStart(2, '0')}@growl.seed`;
  const name = FIRST[i - 1];
  const pathKey = CATEGORY_PATHS[(i - 1) % CATEGORY_PATHS.length];
  const second = CATEGORY_PATHS[(i + 3) % CATEGORY_PATHS.length];
  const cats = i % 3 === 0 ? [pathKey, second] : [pathKey];
  const isInstructor = i <= 5 ? 1 : 0;
  const points = 80 + i * 7 + (isInstructor ? 200 : 0);
  const meta = JSON.stringify({
    username: `${name}${i}`,
    avatar: `https://i.pravatar.cc/150?img=${(i % 70) + 1}`,
    categories: cats,
  });
  userRows.push(
    `  ('${id}', '${email}', '${PASS_HASH}', ${points}, ${isInstructor}, 0, '${esc(meta)}', 1, NULL, NULL, datetime('now', '-${i} days'), datetime('now'))`
  );
}
lines.push(userRows.join(',\n') + ';');
lines.push('');

// Posts — 120
lines.push('INSERT OR IGNORE INTO posts (id, user_id, image_url, caption, category, subcategory, engagement_score, metadata, created_at, updated_at) VALUES');
const postRows = [];
for (let i = 1; i <= 120; i++) {
  const userIdx = ((i - 1) % 40) + 1;
  const uid = `dense-u-${String(userIdx).padStart(2, '0')}`;
  const pathKey = CATEGORY_PATHS[(i - 1) % CATEGORY_PATHS.length];
  const hoursAgo = (i % 72) + 1;
  postRows.push(
    `  ('dense-post-${String(i).padStart(3, '0')}', '${uid}', '${IMAGE_SEEDS[i % IMAGE_SEEDS.length]}', '${esc(CAPTIONS[i % CAPTIONS.length])}', '${parentCat(pathKey)}', ${subCat(pathKey) ? `'${subCat(pathKey)}'` : 'NULL'}, ${10 + (i % 50)}, '{}', datetime('now', '-${hoursAgo} hours'), datetime('now', '-${hoursAgo} hours'))`
  );
}
lines.push(postRows.join(',\n') + ';');
lines.push('');

// Stories — 40
lines.push('INSERT OR IGNORE INTO stories (id, user_id, image_url, caption, views, expires_at, created_at, updated_at) VALUES');
const storyRows = [];
for (let i = 1; i <= 40; i++) {
  const uid = `dense-u-${String(i).padStart(2, '0')}`;
  storyRows.push(
    `  ('dense-story-${String(i).padStart(3, '0')}', '${uid}', '${IMAGE_SEEDS[i % IMAGE_SEEDS.length]}', 'Story check-in', 0, datetime('now', '+20 hours'), datetime('now', '-${i % 20} hours'), datetime('now', '-${i % 20} hours'))`
  );
}
lines.push(storyRows.join(',\n') + ';');
lines.push('');

// Likes — sample engagement
lines.push('INSERT OR IGNORE INTO post_engagement (id, post_id, user_id, type, content, created_at) VALUES');
const engRows = [];
let eng = 0;
for (let p = 1; p <= 80; p++) {
  for (let u = 1; u <= 3; u++) {
    eng++;
    const voter = ((p + u * 7) % 40) + 1;
    engRows.push(
      `  ('dense-like-${eng}', 'dense-post-${String(p).padStart(3, '0')}', 'dense-u-${String(voter).padStart(2, '0')}', 'like', NULL, datetime('now', '-${p} hours'))`
    );
  }
}
// a few comments
for (let c = 1; c <= 30; c++) {
  eng++;
  engRows.push(
    `  ('dense-cmt-${c}', 'dense-post-${String(c).padStart(3, '0')}', 'dense-u-${String(((c * 3) % 40) + 1).padStart(2, '0')}', 'comment', 'Nice progress!', datetime('now', '-${c} hours'))`
  );
}
lines.push(engRows.join(',\n') + ';');
lines.push('');

// Friendships: mutual pairs among dense users + link to demo-core-user
lines.push('INSERT OR IGNORE INTO user_relationships (id, user_id, target_user_id, type, created_at) VALUES');
const relRows = [];
let rel = 0;
for (let i = 1; i <= 40; i++) {
  const a = `dense-u-${String(i).padStart(2, '0')}`;
  const bIdx = (i % 40) + 1;
  if (bIdx === i) continue;
  const b = `dense-u-${String(bIdx).padStart(2, '0')}`;
  rel++;
  relRows.push(`  ('dense-rel-${rel}-a', '${a}', '${b}', 'friend', datetime('now'))`);
  rel++;
  relRows.push(`  ('dense-rel-${rel}-b', '${b}', '${a}', 'friend', datetime('now'))`);
}
// Connect demo-core-user to first 12 dense users (if core seeded)
for (let i = 1; i <= 12; i++) {
  const b = `dense-u-${String(i).padStart(2, '0')}`;
  rel++;
  relRows.push(`  ('dense-rel-core-${i}-a', 'demo-core-user', '${b}', 'friend', datetime('now'))`);
  rel++;
  relRows.push(`  ('dense-rel-core-${i}-b', '${b}', 'demo-core-user', 'friend', datetime('now'))`);
}
lines.push(relRows.join(',\n') + ';');
lines.push('');

// Endorsements: give dense-u-06 enough votes from same-category peers to be near/at claim
// dense-u-06 uses CATEGORY_PATHS[5] = art:violin — voters with art:* 
lines.push('-- Endorsements toward near-eligible candidate dense-u-06 (art cohort)');
lines.push('INSERT OR IGNORE INTO instructor_votes (id, user_id, candidate_id, created_at) VALUES');
const voteRows = [];
// voters 5,7,11,18,31 have art paths in rotation (indices with art)
const artVoters = [5, 7, 8, 18, 19]; // art:* cohort overlapping dense-u-06
artVoters.slice(0, 5).forEach((v, idx) => {
  voteRows.push(
    `  ('dense-vote-06-${idx + 1}', 'dense-u-${String(v).padStart(2, '0')}', 'dense-u-06', datetime('now', '-${idx + 1} days'))`
  );
});
// Also endorse influencers a bit
for (let i = 1; i <= 5; i++) {
  for (let v = 6; v <= 10; v++) {
    voteRows.push(
      `  ('dense-vote-inf-${i}-${v}', 'dense-u-${String(v).padStart(2, '0')}', 'dense-u-${String(i).padStart(2, '0')}', datetime('now', '-${v} hours'))`
    );
  }
}
lines.push(voteRows.join(',\n') + ';');
lines.push('');

const out = path.join(__dirname, 'seed-demo-social-dense.sql');
fs.writeFileSync(out, lines.join('\n') + '\n', 'utf8');
console.log('Wrote', out);
console.log('Users: 40, Posts: 120, Stories: 40');
